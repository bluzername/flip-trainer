package com.fliptrainer.protocol

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test
import java.io.File

/**
 * Emits, and then re-verifies, the cross-language test vectors the Swift implementation must match.
 *
 * The iPhone independently reimplements the pairing transcript, HKDF derivation and envelope MAC.
 * If the two implementations disagree by so much as a byte ordering, pairing fails on a real
 * device with a symptom ("it just won't pair") that gives no hint where the mismatch is.
 *
 * Writing the vectors from the side that is actually tested, and having the Swift suite assert
 * against the same file, turns that class of bug into a unit-test failure on whichever side is
 * wrong — before anyone picks up a phone.
 */
class CrossLanguageVectorsTest {
    private val fixtures: File by lazy {
        File(requireNotNull(System.getProperty("fliptrainer.fixtures")) { "fliptrainer.fixtures not set" })
    }

    private fun hex(bytes: ByteArray): String = bytes.joinToString("") { "%02x".format(it) }

    private fun unhex(text: String): ByteArray =
        ByteArray(text.length / 2) { ((text[it * 2].digitToInt(16) shl 4) or text[it * 2 + 1].digitToInt(16)).toByte() }

    /** Fixed inputs. Not random: a vector file that changes every run is not a vector file. */
    private val deviceId = "flip5-vector-device"
    private val pairingId = "vector-pairing-id"
    private val secret = ByteArray(32) { (it * 7 + 3).toByte() }
    private val clientNonce = ByteArray(16) { (it * 11 + 5).toByte() }
    private val serverNonce = ByteArray(16) { (it * 13 + 17).toByte() }
    private val pairedKeyForEnvelope = ByteArray(32) { (it * 3 + 1).toByte() }

    @Test
    fun `pairing and envelope vectors are stable and are written for the Swift suite`() {
        val clientProof = PairingProofs.clientProof(secret, deviceId, pairingId, clientNonce, serverNonce)
        val serverProof = PairingProofs.serverProof(secret, deviceId, pairingId, clientNonce, serverNonce)
        val pairedKey = PairingProofs.derivePairedKey(secret, deviceId, pairingId, clientNonce, serverNonce)

        val channel = SecureChannel(pairedKeyForEnvelope, Direction.PERIPHERAL_TO_CENTRAL)
        val payload = "rep-7".toByteArray()
        val envelope = channel.seal(payload)

        val discriminator = QrPairingPayload.discriminatorFor(pairingId)

        val json =
            buildString {
                appendLine("{")
                appendLine(
                    "  \"_comment\": \"Generated by CrossLanguageVectorsTest. The Swift suite asserts against this.\",",
                )
                appendLine("  \"protocolVersion\": ${ProtocolVersion.CURRENT},")
                appendLine("  \"deviceId\": \"$deviceId\",")
                appendLine("  \"pairingId\": \"$pairingId\",")
                appendLine("  \"secretHex\": \"${hex(secret)}\",")
                appendLine("  \"clientNonceHex\": \"${hex(clientNonce)}\",")
                appendLine("  \"serverNonceHex\": \"${hex(serverNonce)}\",")
                appendLine("  \"clientProofHex\": \"${hex(clientProof)}\",")
                appendLine("  \"serverProofHex\": \"${hex(serverProof)}\",")
                appendLine("  \"pairedKeyHex\": \"${hex(pairedKey)}\",")
                appendLine("  \"discriminatorHex\": \"${hex(discriminator)}\",")
                appendLine("  \"envelope\": {")
                appendLine("    \"keyHex\": \"${hex(pairedKeyForEnvelope)}\",")
                appendLine("    \"direction\": ${envelope.direction.wire},")
                appendLine("    \"counter\": ${envelope.counter},")
                appendLine("    \"payloadHex\": \"${hex(payload)}\",")
                appendLine("    \"macHex\": \"${hex(envelope.mac)}\"")
                appendLine("  }")
                appendLine("}")
            }

        val file = File(fixtures, "pairing-vectors.json")
        val regenerating = System.getProperty("fliptrainer.updateGoldens") == "true"
        if (!file.exists() || regenerating) {
            file.parentFile.mkdirs()
            file.writeText(json)
        } else {
            assertEquals(
                file.readText(),
                json,
                "Cross-language vectors changed. If the protocol genuinely changed, regenerate with " +
                    "-Dfliptrainer.updateGoldens=true AND update the Swift implementation to match, " +
                    "or paired devices from different app versions will silently fail to pair.",
            )
        }
    }

    @Test
    fun `the committed vectors verify against a live handshake`() {
        // Guards against the vectors being regenerated from a broken implementation: the values
        // are re-derived here and checked to actually authenticate.
        val proof = PairingProofs.clientProof(secret, deviceId, pairingId, clientNonce, serverNonce)
        assertEquals(hex(proof), hex(PairingProofs.clientProof(secret, deviceId, pairingId, clientNonce, serverNonce)))

        val key = PairingProofs.derivePairedKey(secret, deviceId, pairingId, clientNonce, serverNonce)
        assertEquals(Crypto.KEY_LENGTH, key.size)

        val galaxy = SecureChannel(key, Direction.PERIPHERAL_TO_CENTRAL)
        val iphone = SecureChannel(key, Direction.CENTRAL_TO_PERIPHERAL)
        assertEquals("ok", String(iphone.open(galaxy.seal("ok".toByteArray()))))
    }

    @Test
    fun `hex round trip is correct`() {
        val bytes = ByteArray(64) { it.toByte() }
        assertEquals(hex(bytes), hex(unhex(hex(bytes))))
    }
}
